import Groq from "groq-sdk";

import { aiConfig } from "../../../config/ai.config";

export class GroqService {
  private client: Groq | null = null;

  private getClient(): Groq {
    if (!aiConfig.apiKey) {
      throw new Error(
        "GROQ_API_KEY is missing. Add a valid key in apps/api/.env.",
      );
    }

    if (!this.client) {
      this.client = new Groq({
        apiKey: aiConfig.apiKey,
      });
    }

    return this.client;
  }

  private normalizeProviderError(error: unknown): never {
    const message =
      error instanceof Error ? error.message : String(error);

    if (
      message.includes("Invalid API Key") ||
      message.includes("invalid_api_key") ||
      message.includes("401")
    ) {
      throw new Error(
        "Groq rejected the API key. Update GROQ_API_KEY in apps/api/.env with a valid key from https://console.groq.com/keys.",
      );
    }

    if (
      message.includes("model_not_found") ||
      message.includes("does not exist") ||
      message.includes("not found")
    ) {
      throw new Error(
        "Groq chat model is unavailable. Update GROQ_CHAT_MODEL in apps/api/.env to a supported Groq chat model such as openai/gpt-oss-120b. Embeddings continue to use Ollama nomic-embed-text.",
      );
    }

    throw error;
  }

  async generateText(
    prompt: string,
  ): Promise<string> {
    try {
      const response =
        await this.getClient().chat.completions.create({
          model: aiConfig.chatModel,
          messages: [{ role: "user", content: prompt }],
          temperature: aiConfig.temperature,
          max_tokens: 2048,
        });

      return (
        response.choices?.[0]?.message?.content ?? ""
      );
    } catch (error) {
      return this.normalizeProviderError(error);
    }
  }

  async generateEmbedding(
    text: string,
  ): Promise<number[]> {
    throw new Error(
      "Embeddings are generated by Ollama via the embeddings service; Groq is chat-only.",
    );
  }

  async generateEmbeddings(
    texts: string[],
  ): Promise<number[][]> {
    throw new Error(
      "Embeddings are generated by Ollama via the embeddings service; Groq is chat-only.",
    );
  }
}

export const groqService = new GroqService();
export const geminiService = groqService;